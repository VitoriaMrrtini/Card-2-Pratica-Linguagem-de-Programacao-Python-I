# Atribui as variáveis x e y valores inteiros
x = 7
y = 5

# Verifica se x é maior que y
print(x > y)
# Verifica se x é maior ou igual a y
print(x >= y)
# Verifica se x é menor que y
print(x < y)
# Verifica se x é maior ou igual a y
print(x <= y)
# Verifica se x é igual a y
print(x == y)
# Verifica se x é diferente de y
print(x != y)

# Compara uma string com um int
print("5" != 5)  # São considerados de tipos diferentes então retorna True
