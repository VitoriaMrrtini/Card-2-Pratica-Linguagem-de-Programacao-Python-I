# Atribui a variável resultado o valor 2
resultado = 2
# Pega o valor de resultado e soma com ele mesmo
resultado += resultado  # resultado = resultado + resultado
# Pega o valor de resultado e subtrai 1 dele mesmo
resultado -= 1  # resultado = resultado - 1
# Pega o valor de resultado e multiplica 4 dele mesmo
resultado *= 4  # resultado = resultado * 4
# Pega o valor de resultado e dívide 2 dele mesmo
resultado /= 2  # resultado = resultado / 2
# Pega o valor de resultado faz o modulo de 6 por ele mesmo
resultado %= 6  # resultado = resultado % 6

# Imprime o valor final de resultado
print(resultado)
