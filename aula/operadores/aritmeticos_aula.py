# Cria duas variáveis x e y inteiras
x = 30
y = 3

# Soma x e y
print(x + y)  # 33
# Subtrai y de x
print(x - y)  # 27
# Multiplica x e y
print(x * y)  # 90
# Divíde x por y, resultando em um valor do tipo float
print(x / y)  # 10.0
# O modulo retorna o resto da dívisão inteira de x por y
print(x % y)  # 0

# Cria duas variáveis par e ímpar
par = 34
impar = 33

"""Compara as váriaveis se o resultado for diferente de 0 é ímpar,
caso contrario informa se é par"""
print(par % 2 == 0)  # True
"""Compara as váriaveis se o resultado for diferente de 1 é par,
caso contrario informa se é ímpar"""
print(impar % 2 == 1)  # True
