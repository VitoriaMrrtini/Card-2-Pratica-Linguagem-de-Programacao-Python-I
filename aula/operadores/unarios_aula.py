# Atribui a variável y o valor 4
y = 4

# O "not" inverte o valor booleano
print(not False)
print(not True)

# Dois sinais de menos (--) resulta em um positivo (+)
# -- = +
# ++ = +
# +- = -
# -+ = -
print(--3)  # equivale a -(-3) = 3
# A variável altera por conta do operador unário
print(-y)  # -4
# Continua sendo "3"
print(+3)  # 3

# Atribui outra variável o valor 12
w = 12
""" A linguagem python não possui operadores de incremento (++)
 e decremento (--) igual ao c/c++, para fazer esses decrementos usamos,
 por exemplo w-=1 ou w+=1"""
# w++
# Imprime o valor de w
print(w)
